/**
 * Writes frontend/lib/generated/modules.json from the backend's module registry,
 * so the app's menus and page guard use the same list as the API.
 *
 *   node scripts/genModules.js
 *
 * tests/modulesJson.test.js fails if the file is out of date.
 */
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "../../frontend/lib/generated/modules.json");

const build = () => {
  const modules = require("../src/config/modules");
  const { PAGES } = require("../src/config/modulePages");
  const { MANIFESTS } = require("../src/modules/catalog");
  const pages = [...PAGES, ...MANIFESTS.flatMap((m) => (m.pages || []).map((p) => [p, m.key]))]
    // Longest first: the first prefix that matches is the most specific
    .sort((a, b) => b[0].length - a[0].length || a[0].localeCompare(b[0]));
  return {
    note: "Generated by backend/scripts/genModules.js — do not edit by hand.",
    modules: modules.MODULES.map((m) => ({
      key: m.key,
      label: m.label,
      core: Boolean(m.core),
      defaultOn: Boolean(m.defaultOn),
      staffOnly: m.audience === "staff",
      customerOptIn: Boolean(m.customerOptIn),
      orgWide: Boolean(m.orgWide)
    })),
    pages
  };
};

const render = () => `${JSON.stringify(build(), null, 2)}\n`;

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, render());
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}

module.exports = { render, OUT };
